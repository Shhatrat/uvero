static const int LUT_SIZE = sizeof(LUT) / sizeof(LUT[0]);

inline uint8_t lookupSpeed(const uint8_t* key, int keyLen) {
    for (int i = 0; i < LUT_SIZE; i++) {
        if (LUT[i].keyLen == keyLen && memcmp(LUT[i].key, key, keyLen) == 0)
            return LUT[i].speed10;
    }
    return 0;
}
